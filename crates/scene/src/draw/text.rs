use super::Panel;

pub(super) fn label(panel: &mut Panel, text: &str, x: f32, y: f32, scale: f32, color: [f32; 3]) {
    for (index, letter) in text.bytes().enumerate() {
        let start = x + 6.0 * index as f32 * scale;
        for (row, bits) in glyph(letter).into_iter().enumerate() {
            for col in 0..5 {
                if bits & (16 >> col) != 0 {
                    panel.rect(
                        [
                            start + col as f32 * scale,
                            y + row as f32 * scale,
                            scale,
                            scale,
                        ],
                        color,
                    );
                }
            }
        }
    }
}

